#!/usr/bin/env python3
"""Gemini API（無料枠）で当日の台本を作る＋PDCA。

入力: スプレッドシートの過去ログ（再生数つき）と蓄積された改善ルール
出力: 質問・回答・コメント文の材料・本の検索キーワード・新しい改善ルール
Gemini が失敗した場合は内蔵の予備台本（オリジナル3本）から未使用のものを出す。
"""
import json
import os
import time

FALLBACK_SCRIPTS = [
    {
        "question": "会社の飲み会、正直行きたくありません。うまく断れますか？",
        "answer": "大丈夫です。「行けたら行きます」は、日本語における丁寧な不参加の表明として古くから親しまれています。今日は心置きなく、家でゆっくり休んでください。",
        "comment_lead": "飲み会の断り方に悩む夜、ありませんか。今日もおつかれさまです。",
        "book_keyword": "断る力 コミュニケーション 本",
        "new_rule": "",
    },
    {
        "question": "月曜の朝、メールを開くのが怖いです。",
        "answer": "メールは開けた瞬間に現実になりますが、開ける前はまだ可能性のままです。まず深呼吸を3回。それから1通だけ、優しそうな件名のものから開いてみてください。",
        "comment_lead": "月曜の朝の inbox は、だれにとっても少し怖いものです。",
        "book_keyword": "仕事の不安 心が軽くなる 本",
        "new_rule": "",
    },
    {
        "question": "買ったまま読んでいない本が5冊あります。",
        "answer": "積読は読書の前段階ではなく、すでに立派な趣味のひとつです。本棚の5冊は、未来のあなたへの贈り物として静かに待機中です。焦らず、今日は1ページからどうぞ。",
        "comment_lead": "積読仲間のみなさん、今日も本棚が充実していますね。",
        "book_keyword": "読書習慣 本との付き合い方 本",
        "new_rule": "",
    },
]

PROMPT_TEMPLATE = """あなたは縦型ショート動画シリーズ『15秒のひとことポスト』の構成作家兼アナリストです。
このシリーズは、架空の相談窓口に届いた小さなお悩み（質問カード）に、
丁寧でユーモアのある「神回答」が返ってくる、15〜20秒の動画です。

# これまでの投稿と成績（新しい順ではなく時系列順）
{history}

# これまでに蓄積された改善ルール
{rules}

# あなたの仕事
1. 成績データを眺め、どんな質問・回答が伸びているか傾向を読む（PDCAの分析）。
2. その分析を反映して、今日の新しい台本を1本作る。
3. 傾向から言える改善ルールを1つだけ提案する（既存ルールの繰り返しは禁止。
   データから言えない場合は空文字にする）。

# 台本の制約（必ず守ること）
- 質問: 日常の小さな悩み。読み上げて約5秒（30字程度まで）。過去の質問と重複禁止。
- 回答: 読み上げて約12秒（60〜80字）。丁寧で優しく、クスッと笑える比喩や言い換えを1つ入れる。
- 実在の人物・団体・商品・書籍名は出さない。医療・法律・金銭の断定的アドバイスはしない。
  専門家の相談窓口を名乗らない。誰かを傷つける内容、煽り、誇大表現は禁止。
- comment_lead: 投稿コメントの冒頭1文。その日の悩みに寄り添う優しい言葉（40字程度）。
- book_keyword: その悩みに寄り添う本を Amazon で探すための検索キーワード
  （例「朝 起きられない 習慣 本」）。実在しそうな具体的な書名は書かず、主題の言葉にする。

# 出力形式（JSONのみ。前置き・コードフェンス禁止）
{{"question": "...", "answer": "...", "comment_lead": "...",
  "book_keyword": "...", "new_rule": "..."}}
"""


def _history_text(log_rows, limit=14):
    rows = [r for r in log_rows if r.get("動画ID")][-limit:]
    if not rows:
        return "（まだ投稿データがありません。1本目の実績: 布団から出られない悩みは鉄板の共感ネタでした）"
    lines = []
    for r in rows:
        lines.append(
            f"- 質問「{r['質問']}」 再生数={r['再生数'] or '未取得'} "
            f"高評価={r['高評価'] or '未取得'} 平均視聴秒={r['平均視聴秒'] or '未取得'}")
    return "\n".join(lines)


def _rules_text(rules):
    if not rules:
        return "（まだルールはありません）"
    return "\n".join(f"- {r}" for r in rules)


def _fallback(log_rows):
    used = {r.get("質問", "") for r in log_rows}
    for s in FALLBACK_SCRIPTS:
        if s["question"] not in used:
            return dict(s)
    return dict(FALLBACK_SCRIPTS[0])


def generate(log_rows, rules):
    """台本 dict を返す。使用経路も print する。"""
    api_key = os.environ.get("GEMINI_API_KEY", "")
    model = os.environ.get("GEMINI_MODEL", "").strip() or "gemini-3.8-flash"
    if not api_key:
        print("[script] GEMINI_API_KEY not set; using fallback script")
        return _fallback(log_rows)
    try:
        from google import genai
        from google.genai import types
        client = genai.Client(api_key=api_key)
        prompt = PROMPT_TEMPLATE.format(
            history=_history_text(log_rows), rules=_rules_text(rules))
        res = None
        last_err = None
        # 503（混雑）など一時的な失敗に備えて最大3回まで再試行する
        for attempt in range(3):
            try:
                res = client.models.generate_content(
                    model=model,
                    contents=prompt,
                    config=types.GenerateContentConfig(
                        response_mime_type="application/json", temperature=1.0),
                )
                break
            except Exception as e:
                last_err = e
                print(f"[script] Gemini attempt {attempt + 1} failed ({e})")
                if attempt < 2:
                    time.sleep(20 * (attempt + 1))
        if res is None:
            raise RuntimeError(f"Gemini failed after retries: {last_err}")
        data = json.loads(res.text)
        for key in ("question", "answer", "comment_lead", "book_keyword"):
            if not str(data.get(key, "")).strip():
                raise ValueError(f"missing field: {key}")
        data.setdefault("new_rule", "")
        print(f"[script] generated by Gemini ({model})")
        return data
    except Exception as e:
        print(f"[script] Gemini failed ({e}); using fallback script")
        return _fallback(log_rows)
